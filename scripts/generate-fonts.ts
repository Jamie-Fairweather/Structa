/**
 * Trims the vendored TTFs in fonts/ for shipping and writes into generated/:
 * - fonts/*.ttf: each face cut to the shared character ranges, with every
 *   OpenType layout table dropped and every name record kept.
 * - font-metrics.ts: per-face advance widths for the shared character
 *   ranges, plus vertical metrics, read from those trimmed files. The text
 *   module measures and wraps with these tables.
 * - font-files.ts: each trimmed file as a data: URL. structa.mjs embeds
 *   these, and SVGs carry the ones they use.
 *
 * Run with: bun run generate (typecheck, test and build run it first).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CHARACTER_RANGES, FACES, type FaceId, type FaceMetricsData } from "../src/text/faces";
import { trimFont } from "./lib/subset";
import { readTtf } from "./lib/ttf";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const generated = join(root, "generated");

const FONT_FILES: readonly (readonly [FaceId, string])[] = [
  ["inter-regular", "fonts/inter/Inter-Regular.ttf"],
  ["inter-semibold", "fonts/inter/Inter-SemiBold.ttf"],
  ["inter-bold", "fonts/inter/Inter-Bold.ttf"],
  ["inter-semibold-italic", "fonts/inter/Inter-SemiBoldItalic.ttf"],
  ["mono-regular", "fonts/jetbrains-mono/JetBrainsMono-Regular.ttf"],
  ["mono-italic", "fonts/jetbrains-mono/JetBrainsMono-Italic.ttf"],
];

function faceMetrics(face: FaceId, bytes: Uint8Array): FaceMetricsData {
  const font = readTtf(bytes);
  const runs: [number, number[]][] = [];
  let current: [number, number[]] | undefined;
  for (const [first, last] of CHARACTER_RANGES) {
    for (let codePoint = first; codePoint <= last; codePoint++) {
      const advance = font.advance(codePoint);
      if (advance === undefined) {
        current = undefined;
        continue;
      }
      if (current && current[0] + current[1].length === codePoint) {
        current[1].push(advance);
      } else {
        current = [codePoint, [advance]];
        runs.push(current);
      }
    }
  }
  return {
    face,
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    missingAdvance: font.missingAdvance,
    runs,
  };
}

const fonts = FACES.map(({ id }) => {
  const entry = FONT_FILES.find(([face]) => face === id);
  if (!entry) throw new Error(`no font file listed for face ${id}`);
  const trimmed = `fonts/${basename(entry[1])}`;
  writeIfChanged(trimmed, trimFont(readFileSync(join(root, entry[1])), CHARACTER_RANGES));
  // Everything after this reads the trimmed file, exactly as it ships.
  return { face: id, bytes: readFileSync(join(generated, trimmed)) };
});

const metrics = fonts
  .map(({ face, bytes }) => {
    const m = faceMetrics(face, bytes);
    const runs = m.runs.map(([start, widths]) => `      [${start}, [${widths.join(", ")}]],`).join("\n");
    return [
      "  {",
      `    face: ${JSON.stringify(m.face)},`,
      `    unitsPerEm: ${m.unitsPerEm},`,
      `    ascender: ${m.ascender},`,
      `    descender: ${m.descender},`,
      `    missingAdvance: ${m.missingAdvance},`,
      "    runs: [",
      runs,
      "    ],",
      "  },",
    ].join("\n");
  })
  .join("\n");

writeIfChanged(
  "font-metrics.ts",
  `// Generated by scripts/generate-fonts.ts from the TTFs in fonts/. Do not edit.
import type { FaceMetricsData } from "../src/text/faces";

export const FONT_METRICS: readonly FaceMetricsData[] = [
${metrics}
];
`,
);

const files = fonts
  .map(({ face, bytes }) => `  [${JSON.stringify(face)}, "data:font/ttf;base64,${Buffer.from(bytes).toString("base64")}"],`)
  .join("\n");

writeIfChanged(
  "font-files.ts",
  `// Generated by scripts/generate-fonts.ts from the TTFs in fonts/. Do not edit.
import type { FaceId } from "../src/text/faces";

/** Each face's trimmed TTF as a data: URL, for @font-face rules. */
export const FONT_FILES: ReadonlyMap<FaceId, string> = new Map<FaceId, string>([
${files}
]);
`,
);

function writeIfChanged(name: string, content: string | Uint8Array): void {
  const file = join(generated, name);
  const bytes = typeof content === "string" ? Buffer.from(content, "utf8") : content;
  mkdirSync(dirname(file), { recursive: true });
  if (!existsSync(file) || !readFileSync(file).equals(bytes)) {
    writeFileSync(file, bytes);
    console.log(`wrote ${file}`);
  }
}

// Draws the pictures for README.md and EXAMPLES.md with the built structa.mjs,
// and writes EXAMPLES.md: every file in examples/, in light and dark.
// Run `bun run docs-images` after a change to how diagrams look, or to the examples.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const cli = join(root, "dist", "structa", "structa.mjs");
const images = join(root, "docs", "images");
const THEMES = ["light", "dark"] as const;

/** Diagram types in the order EXAMPLES.md lists them, with their section headings. */
const SECTIONS = [
  { type: "class", heading: "Class diagrams" },
  { type: "er", heading: "ER diagrams" },
  { type: "flow", heading: "Flowcharts" },
  { type: "architecture", heading: "Architecture diagrams" },
] as const;

/** What each example shows off, used as its heading. An example missing here falls back to its file name. */
const SHOWS = new Map<string, string>([
  ["class", "A simple class diagram"],
  ["class-areas", "Classes tagged with the area they belong to"],
  ["class-grouped", "UML classes with change status, in nested area boxes"],
  ["class-hierarchy", "Interfaces, abstract classes and inheritance"],
  ["class-kinds", "Interface, abstract, enum and record classes"],
  ["class-right", "Every UML line, laid out left to right"],
  ["class-status", "Classes and members with change status"],
  ["er", "Tables, keys and crow's-foot lines"],
  ["er-areas", "Tables in nested area boxes, with a two-column key"],
  ["er-down", "Tables laid out top to bottom"],
  ["er-status", "A schema change"],
  ["flow", "Every flowchart shape, with decisions and a loop"],
  ["flow-areas", "Area boxes as swimlanes, with a note and a loop"],
  ["flow-notes", "Notes attached to steps"],
  ["flow-right", "A flowchart laid out left to right"],
  ["flow-status", "A process that changes"],
  ["architecture", "Every component kind, with call and async lines"],
  ["architecture-change-map", "A change across a whole system, in nested area boxes"],
  ["architecture-change-map-tags", "The same change, with area tags on the cards instead of boxes"],
  ["architecture-classes", "Component cards and class cards together, with change status"],
]);

const byCodeUnit = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** Draws one JSON file to docs/images/<name>-<theme>.svg with plain Node, as agents run it (elkjs hangs under Bun). */
function draw(source: string, name: string, theme: (typeof THEMES)[number]): string {
  const file = `${name}-${theme}.svg`;
  execFileSync("node", [cli, join(root, source), "--theme", theme, "-o", join(images, file)], { stdio: "inherit" });
  return file;
}

rmSync(images, { recursive: true, force: true });
mkdirSync(images, { recursive: true });

// The README's tea flowchart is drawn from its own file, light only.
draw("docs/readme/quick-start.json", "quick-start", "light");

const examples = readdirSync(join(root, "examples"))
  .filter((file) => file.endsWith(".json"))
  .map((file) => {
    const name = file.slice(0, -".json".length);
    const { type } = JSON.parse(readFileSync(join(root, "examples", file), "utf8")) as { type: string };
    return { file, name, type };
  });

const lines = [
  "<!-- Generated by `bun run docs-images` from the files in examples/. Edit those files or scripts/docs-images.ts, not this page. -->",
  "",
  "# Examples",
  "",
  "Every example that ships with Structa, drawn by Structa itself in the light and the dark theme. Each one is a file in [`examples/`](examples): copy one as a starting point, or print one with `node structa.mjs example <type>`.",
  "",
  ...SECTIONS.map(({ heading }) => `- [${heading}](#${heading.toLowerCase().replaceAll(" ", "-")})`),
];

for (const { type, heading } of SECTIONS) {
  // The plain example for each type first, then the rest by name.
  const inSection = examples
    .filter((example) => example.type === type)
    .sort((a, b) => (a.name === type ? -1 : b.name === type ? 1 : byCodeUnit(a.name, b.name)));
  lines.push("", `## ${heading}`);
  for (const { file, name } of inSection) {
    const shows = SHOWS.get(name) ?? name;
    lines.push("", `### ${shows}`, "", `From [\`examples/${file}\`](examples/${file}).`);
    for (const theme of THEMES) {
      const image = draw(`examples/${file}`, name, theme);
      const label = theme === "light" ? "Light" : "Dark";
      lines.push("", `**${label}**`, "", `<img alt="${shows}, in the ${theme} theme." src="docs/images/${image}">`);
    }
  }
}

writeFileSync(join(root, "EXAMPLES.md"), `${lines.join("\n")}\n`);
console.log(`wrote ${join(root, "EXAMPLES.md")} and ${examples.length * THEMES.length + 1} pictures in ${images}`);

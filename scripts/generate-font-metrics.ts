/**
 * Reads the vendored TTFs in fonts/ and writes generated/font-metrics.ts:
 * per-face advance widths for the shared character ranges, plus vertical
 * metrics. The text module measures and wraps with these tables.
 *
 * Run with: bun run generate (typecheck and test run it first).
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CHARACTER_RANGES, FACES, type FaceId, type FaceMetricsData } from "../src/text/faces";
import { readTtf } from "./lib/ttf";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "generated", "font-metrics.ts");

const FONT_FILES: readonly (readonly [FaceId, string])[] = [
  ["inter-regular", "fonts/inter/Inter-Regular.ttf"],
  ["inter-semibold", "fonts/inter/Inter-SemiBold.ttf"],
  ["inter-bold", "fonts/inter/Inter-Bold.ttf"],
  ["inter-semibold-italic", "fonts/inter/Inter-SemiBoldItalic.ttf"],
  ["mono-regular", "fonts/jetbrains-mono/JetBrainsMono-Regular.ttf"],
  ["mono-italic", "fonts/jetbrains-mono/JetBrainsMono-Italic.ttf"],
];

function faceMetrics(face: FaceId, file: string): FaceMetricsData {
  const font = readTtf(readFileSync(join(root, file)));
  const runs: [number, number[]][] = [];
  let current: [number, number[]] | undefined;
  for (const [first, last] of CHARACTER_RANGES) {
    for (let codePoint = first; codePoint <= last; codePoint++) {
      const advance = font.advance(codePoint);
      if (advance === undefined) {
        current = undefined;
        continue;
      }
      if (current && current[0] + current[1].length === codePoint) {
        current[1].push(advance);
      } else {
        current = [codePoint, [advance]];
        runs.push(current);
      }
    }
  }
  return {
    face,
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    missingAdvance: font.missingAdvance,
    runs,
  };
}

const metrics = FACES.map(({ id }) => {
  const entry = FONT_FILES.find(([face]) => face === id);
  if (!entry) throw new Error(`no font file listed for face ${id}`);
  return faceMetrics(id, entry[1]);
});

const body = metrics
  .map((m) => {
    const runs = m.runs.map(([start, widths]) => `      [${start}, [${widths.join(", ")}]],`).join("\n");
    return [
      "  {",
      `    face: ${JSON.stringify(m.face)},`,
      `    unitsPerEm: ${m.unitsPerEm},`,
      `    ascender: ${m.ascender},`,
      `    descender: ${m.descender},`,
      `    missingAdvance: ${m.missingAdvance},`,
      "    runs: [",
      runs,
      "    ],",
      "  },",
    ].join("\n");
  })
  .join("\n");

const source = `// Generated by scripts/generate-font-metrics.ts from the TTFs in fonts/. Do not edit.
import type { FaceMetricsData } from "../src/text/faces";

export const FONT_METRICS: readonly FaceMetricsData[] = [
${body}
];
`;

mkdirSync(dirname(outFile), { recursive: true });
if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== source) {
  writeFileSync(outFile, source);
  console.log(`wrote ${outFile}`);
}
